HUDOverlay::HUDOverlay() : width(0), height(0) {}
HUDOverlay::~HUDOverlay() {}

void HUDOverlay::resize(int w, int h) {
    width = w;
    height = h;
    pixels.resize(w * h, 0);
}

void HUDOverlay::clear() {
    std::fill(pixels.begin(), pixels.end(), 0);
}

void HUDOverlay::fillRect(int x, int y, int w, int h, uint32_t color) {
    int x0 = std::max(0, x);
    int y0 = std::max(0, y);
    int x1 = std::min(width, x + w);
    int y1 = std::min(height, y + h);

    for (int j = y0; j < y1; ++j) {
        for (int i = x0; i < x1; ++i) {
            pixels[j * width + i] = color;
        }
    }
}

void HUDOverlay::drawRect(int x, int y, int w, int h, uint32_t color) {
    for (int i = x; i < x + w; ++i) {
        if (i >= 0 && i < width) {
            if (y >= 0 && y < height) pixels[y * width + i] = color;
            if (y + h - 1 >= 0 && y + h - 1 < height) pixels[(y + h - 1) * width + i] = color;
        }
    }
    for (int j = y; j < y + h; ++j) {
        if (j >= 0 && j < height) {
            if (x >= 0 && x < width) pixels[j * width + x] = color;
            if (x + w - 1 >= 0 && x + w - 1 < width) pixels[j * width + (x + w - 1)] = color;
        }
    }
}

void HUDOverlay::drawChar(int x, int y, char c, uint32_t color, int scale) {
    if (c < 32 || c > 126) c = '?';
    const uint8_t* glyph = FONT8x8[c - 32];

    for (int row = 0; row < 8; ++row) {
        uint8_t rowBits = glyph[row];
        for (int col = 0; col < 8; ++col) {
            if ((rowBits >> (7 - col)) & 1) {
                for (int sy = 0; sy < scale; ++sy) {
                    for (int sx = 0; sx < scale; ++sx) {
                        int px = x + col * scale + sx;
                        int py = y + row * scale + sy;
                        if (px >= 0 && px < width && py >= 0 && py < height) {
                            pixels[py * width + px] = color;
                        }
                    }
                }
            }
        }
    }
}

void HUDOverlay::drawText(int x, int y, const std::string& text, uint32_t color, int scale) {
    int curX = x;
    int curY = y;
    for (char c : text) {
        if (c == '\n') {
            curX = x;
            curY += 10 * scale;
            continue;
        }
        drawChar(curX, curY, c, color, scale);
        curX += 8 * scale;
    }
}
