bool Overlay::init() {
    if (!prog_.load(find_shader("overlay.vert"), find_shader("overlay.frag")))
        return false;
    u_res_ = prog_.uniform("uResolution");
    glGenVertexArrays(1, &vao_);
    glGenBuffers(1, &vbo_);
    glBindVertexArray(vao_);
    glBindBuffer(GL_ARRAY_BUFFER, vbo_);
    glEnableVertexAttribArray(0);
    glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, 6 * sizeof(float),
                          (void*)0);
    glEnableVertexAttribArray(1);
    glVertexAttribPointer(1, 4, GL_FLOAT, GL_FALSE, 6 * sizeof(float),
                          (void*)(2 * sizeof(float)));
    glBindVertexArray(0);
    return true;
}

void Overlay::begin(int win_w, int win_h) {
    win_w_ = win_w;
    win_h_ = win_h;
    verts_.clear();
}

void Overlay::quad(float x, float y, float w, float h, Rgba c) {
    const float x0 = x, y0 = y, x1 = x + w, y1 = y + h;
    const float v[6][6] = {
        {x0, y0, c.r, c.g, c.b, c.a}, {x1, y0, c.r, c.g, c.b, c.a},
        {x1, y1, c.r, c.g, c.b, c.a}, {x0, y0, c.r, c.g, c.b, c.a},
        {x1, y1, c.r, c.g, c.b, c.a}, {x0, y1, c.r, c.g, c.b, c.a},
    };
    for (auto& row : v)
        for (float f : row) verts_.push_back(f);
}

void Overlay::panel(float x, float y, float w, float h, Rgba c) {
    quad(x, y, w, h, c);
}

void Overlay::text(float x, float y, float scale, const std::string& s,
                   Rgba c) {
    float cx = x;
    for (char raw : s) {
        char ch = (char)std::toupper((unsigned char)raw);
        const Glyph* g = find_glyph(ch);
        if (!g) g = find_glyph('?');
        for (int row = 0; row < 7; ++row)
            for (int col = 0; col < 5; ++col)
                if (g->row[row][col] == '#')
                    quad(cx + col * scale, y + row * scale, scale, scale, c);
        cx += 6.0f * scale;
    }
}

void Overlay::end() {
    if (verts_.empty()) return;
    prog_.use();
    glUniform2f(u_res_, (float)win_w_, (float)win_h_);
    glBindVertexArray(vao_);
    glBindBuffer(GL_ARRAY_BUFFER, vbo_);
    glBufferData(GL_ARRAY_BUFFER, verts_.size() * sizeof(float), verts_.data(),
                 GL_STREAM_DRAW);
    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);
    glDisable(GL_DEPTH_TEST);
    glDrawArrays(GL_TRIANGLES, 0, (int)verts_.size() / 6);
    glBindVertexArray(0);
}
