#!/bin/sh
# Concatenate the shared physics header, shared structs and the Metal sources into one translation unit.
# The app compiles this text at start-up with -[MTLDevice newLibraryWithSource:], so the shader physics is
# literally the same kerr_shared.h that the CPU tests exercise.
set -e
root="$(cd "$(dirname "$0")/.." && pwd)"
out="$1"
{
  echo "// GENERATED by tools/bundle_shaders.sh -- do not edit"
  for f in src/kerr_shared.h src/shared_types.h src/shaders/common.metal src/shaders/raytrace.metal src/shaders/post.metal src/shaders/funnel.metal; do
    echo "// ---- $f"
    grep -v '^#pragma once' "$root/$f" | grep -v '^#include "'
  done
} > "$out"
