inline const Glyph* glyphFor(char cChar) {
    unsigned char c = static_cast<unsigned char>(cChar);
    if (c >= 'a' && c <= 'z') c = static_cast<unsigned char>(c - 'a' + 'A');
    if (c >= '0' && c <= '9') return &kGlyphDigit[c - '0'];
    if (c >= 'A' && c <= 'Z') return &kGlyphLetter[c - 'A'];
    switch (c) {
        case ' ':  return &kGlyphSpace;
        case '!':  return &kGlyphExclaim;
        case '"':  return &kGlyphQuote;
        case '#':  return &kGlyphHash;
        case '%':  return &kGlyphPercent;
        case '&':  return &kGlyphAmp;
        case '\'': return &kGlyphApos;
        case '(':  return &kGlyphLParen;
        case ')':  return &kGlyphRParen;
        case '*':  return &kGlyphStar;
        case '+':  return &kGlyphPlus;
        case ',':  return &kGlyphComma;
        case '-':  return &kGlyphMinus;
        case '.':  return &kGlyphDot;
        case '/':  return &kGlyphSlash;
        case ':':  return &kGlyphColon;
        case ';':  return &kGlyphSemi;
        case '<':  return &kGlyphLt;
        case '=':  return &kGlyphEq;
        case '>':  return &kGlyphGt;
        case '?':  return &kGlyphQuestion;
        case '[':  return &kGlyphLBracket;
        case ']':  return &kGlyphRBracket;
        case '_':  return &kGlyphUnder;
        case '~':  return &kGlyphDeg;
        default:   return &kGlyphPad;
    }
}

